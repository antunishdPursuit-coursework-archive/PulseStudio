#!/usr/bin/env node
/* Pulse Studio — stamps the source revision into a file the server can
 * read at runtime. TEAM-OWNED.
 *
 * WHY THIS EXISTS: a deployed instance should be able to say exactly which
 * commit it is running, and it should be able to say so WITHOUT a `.git`
 * directory in production. The box deploy is a plain `git clone` today, but
 * a deploy is a fact about the box, not about this repository, and nothing
 * here should assume that stays true — a container image built from a
 * tarball, or a rsync of build output only, would have no `.git` to read
 * `git rev-parse HEAD` from at runtime even though the SOURCE that produced
 * it did.
 *
 * So the SHA is resolved once, at BUILD time (`npm run build`, before
 * `tsc`), where a `.git` directory is a safe assumption — this script reads
 * it with `git rev-parse HEAD`, full and unabbreviated — and burned into
 * `app/shared/revision.ts` as a plain string constant. `tsc` compiles it
 * like any other module, and the server imports the compiled constant, not
 * the git command: a runtime environment with no `.git`, or with a
 * different one entirely (a stripped production image, a copy without
 * history) still reports the commit it was actually BUILT from.
 *
 * GENERATED, LIKE THE COMPILED .js BESIDE IT — NOT CHECKED IN. The git law
 * already draws this line for compiled output: ".gitignore covers it,
 * because build artifacts create conflicts the source never had." A
 * checked-in revision file is exactly that kind of artifact wearing a `.ts`
 * extension: it goes stale the moment the NEXT commit lands, and unlike
 * compiled JS nothing regenerates it on every edit — only a build does. A
 * checked-in placeholder invites the opposite failure this whole feature
 * exists to prevent: a deployed instance confidently reporting the WRONG
 * commit because somebody forgot to run the build after editing the
 * placeholder by hand. Regenerating it on every `npm run build` (see
 * `package.json`, which runs this script before `tsc`) means the file can
 * never be older than the source tree it was built from, and there is
 * nothing here for a merge to conflict over — the same property that keeps
 * compiled `.js` out of git in the first place.
 *
 * FAILS THE BUILD rather than stamping a value nothing could verify. A
 * silent "unknown" fallback would ship a server that reports itself
 * unverifiable forever, which defeats the point as completely as reporting
 * the wrong commit would. If this script cannot resolve a full SHA, the
 * build stops here — build inside a git checkout with at least one commit.
 *
 * Run: node scripts/stamp-revision.mjs   (also runs inside `npm run build`
 * and `npm run check`, both before `tsc`)
 */

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { isValidRevision } from "./revision.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "app/shared/revision.ts");

/** The full, unabbreviated SHA of HEAD, or null when nothing could be
 *  read — a shallow, git-less, or history-less checkout, none of which
 *  this script may guess its way around. */
function resolveRevision() {
  try {
    return execFileSync("git", ["-C", ROOT, "rev-parse", "HEAD"], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    }).trim();
  } catch {
    return null;
  }
}

function run() {
  const sha = resolveRevision();
  if (!isValidRevision(sha)) {
    console.error(
      "stamp-revision: could not resolve a full 40-character commit SHA from `git rev-parse HEAD` " +
        `(got ${sha === null ? "no output at all — is this a git checkout with at least one commit?" : JSON.stringify(sha)}). ` +
        "Refusing to stamp a value nothing could verify — a deployed instance that cannot prove which " +
        "commit it runs is worse than one that fails to build. FAIL",
    );
    process.exit(1);
  }

  const contents =
    "/* GENERATED by scripts/stamp-revision.mjs at build time — DO NOT EDIT BY HAND.\n" +
    " * Gitignored, exactly like the compiled .js beside it: this is a build artifact, regenerated\n" +
    " * on every `npm run build` from `git rev-parse HEAD`, so it can never be older than the source\n" +
    " * tree it was built from. See that script for why a checked-in placeholder was rejected. */\n" +
    `export const REVISION = ${JSON.stringify(sha)};\n`;
  writeFileSync(OUT, contents);
  console.log(`stamp-revision: wrote ${sha} to app/shared/revision.ts`);
}

run();
