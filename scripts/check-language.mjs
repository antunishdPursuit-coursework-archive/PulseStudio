#!/usr/bin/env node
/* Pulse Studio — the language gate. TEAM-OWNED.
 *
 * WHY THIS EXISTS: two of the laws every brief repeats had nothing behind
 * them. CLAUDE.md says the words "demo", "example" and "mock" appear
 * NOWHERE, and that no AI is ever a contributor. Both were stated in six
 * separate files and enforced by nobody, so `npm run check` printed 314
 * checks and 0 failures with a violation sitting on line 162 of the root
 * data contract — the first document a new developer reads. By this repo's
 * own standard in docs/README.md, a rule nobody can check is a wish.
 *
 * MENTION IS NOT USE. Every brief that states the law has to name the
 * forbidden words to forbid them. A banned word wrapped in quotes or
 * backticks is being NAMED, and is allowed; the same word running loose in
 * a sentence is being USED, and fails. That single distinction separated
 * all 15 hits in this repo correctly on the day it landed — 13 statements
 * of the law, 2 real violations — so no allowlist file is needed and there
 * is no baseline here to quietly rot into a permanent excuse.
 *
 * IT DOES NOT PUNISH THE PAST. Sixteen commits already on main carry a
 * `Co-authored-by` trailer for an assistant. The git law forbids rewriting
 * published history, so those stay and this gate never looks at them: it
 * reads only the commits the current branch ADDS beyond origin/main. The
 * bleeding stops; the scar is left alone.
 *
 * HONEST LIMITS, because a checker that oversells itself is worse than
 * none:
 *   - Quoting is the whole exemption, so `The "demo" page is live` passes.
 *     A person deliberately evading this gate will succeed; it is aimed at
 *     the accident, which is how all 15 hits actually arose.
 *   - It reads tracked text files only. Binary assets, untracked files and
 *     anything outside `git ls-files` are invisible to it.
 *   - The commit scan needs origin/main. In a shallow CI checkout there may
 *     be no commits to compare, and the gate SAYS the number it scanned
 *     rather than implying it checked more than it did.
 *   - It knows the assistant names in ASSISTANT_NAMES and no others. A new
 *     tool's name has to be added here by hand.
 *
 * Run: node scripts/check-language.mjs   (also runs inside `npm run check`)
 * Prove it still works: node scripts/check-language.mjs --self-test
 */

import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { isCommand } from "./is-command.mjs";

/* Importing this file must never RUN the gate — the self-test and any
 * future check import the functions directly. Only running it as a command
 * performs the check. */
/* Ten gates carried their own copy of this test and all ten were wrong the
 * same way: reached through a symlink the guard went false and the gate
 * exited 0 having checked nothing. See scripts/is-command.mjs. */
const IS_COMMAND = isCommand(import.meta.url);

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

/* Commit subjects and bodies contain newlines, so the git log format below
 * separates fields and records with the ASCII unit and record separators —
 * two bytes no commit message will ever contain. */
const FIELD_SEP = "\u001f";
const RECORD_SEP = "\u001e";

/* The language law's own words, plus the plurals and inflections that carry
 * the same meaning. "demonstrate" and "demotes" are NOT here on purpose:
 * they are different words that merely start the same way, and the word
 * boundaries below keep them out. */
const BANNED_WORDS = [
  "demo",
  "demos",
  "example",
  "examples",
  "mock",
  "mocks",
  "mocked",
  "mocking",
];

/* Names that must never appear as an author or contributor. Assistant names
 * in prose (this file names several) are mentions and pass the same way a
 * banned word in quotes does. */
const ASSISTANT_NAMES = [
  "claude",
  "copilot",
  "cursor",
  "chatgpt",
  "codex",
  "gemini",
];

/* CREDIT, NOT VOCABULARY. The law forbids an assistant being credited as a
 * contributor — it does not forbid the word "generated", and every brief
 * that states the law has to write the trailer's name down. The first
 * version of this gate got that wrong and raised nine false alarms on its
 * first run: eight on the honest build-provenance line each AGENTS.md
 * mirror carries ("generated by scripts/sync-agent-briefs.sh") and one on
 * the sentence in Product D's brief that forbids the trailer. So:
 *   - a trailer only counts in TRAILER FORM, anchored at the start of its
 *     line and followed by a colon, which is the only form git honours;
 *   - "generated with/by" only counts when an assistant is NAMED on the
 *     same line, because a script generating a file is not an author. */
const ATTRIBUTION_PATTERNS = [
  { code: "co-authored-by", re: /^\s*co-authored-by\s*:/i, needsAssistantName: false },
  { code: "generated-with", re: /generated (with|by) /i, needsAssistantName: true },
  { code: "robot-signature", re: /\u{1F916}/u, needsAssistantName: false },
  { code: "assistant-url", re: /claude\.ai\/code|copilot\.github\.com/i, needsAssistantName: false },
];

/* Files whose bytes are not prose. Reading them would produce noise, and
 * the gate states that it skipped them rather than pretending it looked. */
const BINARY_EXTENSIONS = [
  ".woff2", ".woff", ".ttf", ".otf",
  ".webp", ".png", ".jpg", ".jpeg", ".gif", ".ico",
  ".pdf", ".zip", ".mp4", ".webm",
];

function isBinaryPath(file) {
  return BINARY_EXTENSIONS.some((ext) => file.toLowerCase().endsWith(ext));
}

/* ---------- the two rules, as pure functions ---------- */

/** A banned word is a MENTION when the match itself is wrapped in quotes or
 *  backticks. Naming a forbidden word to forbid it is not using it.
 *
 *  It is ALSO a mention when it sits inside a path — preceded by "." or a
 *  slash, or followed by one. You have to be able to write the name of a
 *  file that exists, and the assistant-name rule below already works this
 *  way ("CLAUDE.md is a filename, not a byline"); the two rules simply
 *  disagreed until 2026-08-21.
 *
 *  What changed it: this gate scans CONTENT and never filenames, so a repo
 *  could hold a file named .env.{banned} quite happily while failing any
 *  document that told you to copy it. That is not a rule, it is an
 *  accident, and it surfaced the moment a teammate added exactly that file
 *  by the ordinary dotenv convention. Whether the repo should contain such
 *  a name at all is a separate question, and it belongs to that file's
 *  owner — see docs/REQUESTFOR-A-B-C.md. This function only stops the gate
 *  from punishing everyone who mentions it.
 *
 *  Prose is untouched: in "for {banned}" the preceding character is a
 *  space, so it still fails, which the planted cases hold. */
export function bannedWordHits(line) {
  const hits = [];
  for (const word of BANNED_WORDS) {
    const re = new RegExp(`(.?)\\b(${word})\\b(.?)`, "gi");
    let match;
    while ((match = re.exec(line)) !== null) {
      const before = match[1] ?? "";
      const after = match[3] ?? "";
      const quoted =
        (before === '"' && after === '"') ||
        (before === "`" && after === "`") ||
        (before === "'" && after === "'");
      if (quoted) continue;
      const pathish =
        before === "." || before === "/" || before === "\\" || after === "/";
      if (pathish) continue;
      hits.push({ word: match[2].toLowerCase(), quoted: false });
    }
  }
  return hits;
}

/** Attribution in a body of text. Same mention rule: a law that forbids
 *  `Co-Authored-By` has to write it down. */
export function attributionHits(line) {
  const hits = [];
  for (const { code, re, needsAssistantName } of ATTRIBUTION_PATTERNS) {
    const match = line.match(re);
    if (match === null) continue;
    if (needsAssistantName && assistantAuthorHits(line).length === 0) continue;
    const at = match.index ?? 0;
    const before = at > 0 ? line[at - 1] : "";
    const after = line[at + match[0].length] ?? "";
    const quoted =
      (before === '"' || before === "`" || before === "'") ||
      (after === '"' || after === "`" || after === "'");
    if (quoted) continue;
    hits.push({ code });
  }
  return hits;
}

/** An author or trailer line naming an assistant. Applied to commit
 *  metadata only, where a name is a claim of authorship rather than prose. */
export function assistantAuthorHits(text) {
  const hits = [];
  for (const name of ASSISTANT_NAMES) {
    /* A NAME IN A PATH IS A FILENAME, NOT AN AUTHOR. Every AGENTS.md mirror
     * in this repo says it was "generated by" a script on a line that also
     * names CLAUDE.md, and the first version of this gate read that as an
     * assistant taking credit. A name followed by a dot or a slash is part
     * of a path — CLAUDE.md, .claude/, claude.ai — and is not a byline. */
    if (new RegExp(`\\b${name}\\b(?![./])`, "i").test(text)) hits.push({ name });
  }
  return hits;
}

/* ---------- the self-test ---------- */

function selfTest() {
  /* THE GATE SCANS ITSELF, so the two planted cases that must contain a
   * banned word UNQUOTED are assembled from fragments rather than written
   * out. Writing them plainly would make this file fail its own check, and
   * the alternative — teaching the gate to skip the file that defines it —
   * would carve an exemption that anyone could then use. The assembled
   * string is byte-identical to the real violation it stands for, so the
   * detector is proven against exactly the text it has to catch. */
  const bannedDemo = `D${"emo"}`;
  const bannedExample = `ex${"ample"}`;
  const planted = [
    { label: "loose banned word fails", input: `${bannedDemo} login stands in for auth`, fn: bannedWordHits, want: true },
    /* This case asserted the OPPOSITE until 2026-08-21 — a path-shaped
     * banned word had to fail. It is flipped rather than deleted so the
     * reversal stays visible: the gate never scanned filenames, so the old
     * rule only ever punished documents for naming a file the repo was
     * free to contain. */
    { label: "a path is a name, not the word", input: `cp .env.${bannedExample} .env`, fn: bannedWordHits, want: false },
    { label: "...but the same word in prose still fails", input: `for ${bannedExample}, see the brief`, fn: bannedWordHits, want: true },
    { label: "...and a directory path is a name too", input: `app/${bannedExample}/index.html`, fn: bannedWordHits, want: false },
    { label: "quoted mention passes", input: 'the words "demo", "example", and "mock" appear nowhere', fn: bannedWordHits, want: false },
    { label: "backticked mention passes", input: "no `example` may ship", fn: bannedWordHits, want: false },
    { label: "demonstrate is a different word", input: "these demonstrate the rule", fn: bannedWordHits, want: false },
    { label: "demotes is a different word", input: "the gate demotes the finding", fn: bannedWordHits, want: false },
    { label: "loose trailer fails", input: "Co-authored-by: Cursor <cursoragent@cursor.com>", fn: attributionHits, want: true },
    { label: "generated-with and no name named is not a byline", input: "Generated with an assistant", fn: attributionHits, want: false },
    { label: "quoted trailer passes", input: "no `Co-Authored-By`, no assistant names", fn: attributionHits, want: false },
    { label: "clean prose passes", input: "The studio flags members who have gone quiet.", fn: attributionHits, want: false },
    // The nine false alarms the first version of this gate raised. Each is a
    // real line from this repo, kept here so the gate can never re-learn them.
    { label: "a script generating a file is not an author", input: "> MIRROR of the CLAUDE.md in this folder, generated by scripts/sync-agent-briefs.sh.", fn: attributionHits, want: false },
    { label: "the law forbidding the trailer is not the trailer", input: '- No AI is ever a contributor: no Co-Authored-By, no "generated with", no', fn: attributionHits, want: false },
    { label: "a trailer mid-sentence is prose, not a trailer", input: "we never add a Co-Authored-By line", fn: attributionHits, want: false },
    { label: "a real trailer at line start still fails", input: "Co-Authored-By: Someone <someone@invalid>", fn: attributionHits, want: true },
    { label: "generated with a named assistant fails", input: "Generated with Claude Code", fn: attributionHits, want: true },
    { label: "assistant author name fails", input: "Cursor <cursoragent@cursor.com>", fn: assistantAuthorHits, want: true },
    { label: "human author name passes", input: "Rensley R. <rensley@pulsestudio.invalid>", fn: assistantAuthorHits, want: false },
    { label: "CLAUDE.md is a filename, not a byline", input: "read CLAUDE.md first", fn: assistantAuthorHits, want: false },
    { label: "the .claude directory is a path, not a byline", input: "ignore .claude/settings.local.json", fn: assistantAuthorHits, want: false },
  ];

  let failed = 0;
  for (const c of planted) {
    const got = c.fn(c.input).length > 0;
    if (got !== c.want) {
      failed += 1;
      console.error(`  self-test MISS — ${c.label}: wanted ${c.want ? "a hit" : "no hit"}, got ${got ? "a hit" : "no hit"}`);
    }
  }
  console.log(`self-test: ${planted.length} planted cases, ${planted.length - failed} behaved, ${failed} did not.`);
  console.log(
    failed === 0
      ? "self-test PASSED — the gate can still fail. (Says nothing about which files it scans; see the limits above.)"
      : "self-test FAILED — the gate is blind.",
  );
  process.exit(failed === 0 ? 0 : 1);
}

/* ---------- the run ---------- */

function trackedFiles() {
  const out = execFileSync("git", ["-C", ROOT, "ls-files"], { encoding: "utf8" });
  return out.split("\n").filter((f) => f !== "");
}

/** Only the commits this branch ADDS. Published history is not ours to
 *  rewrite, so it is not ours to fail on either. */
function newCommits() {
  try {
    execFileSync("git", ["-C", ROOT, "rev-parse", "--verify", "origin/main"], { stdio: "pipe" });
  } catch {
    return { available: false, commits: [] };
  }
  const out = execFileSync(
    "git",
    ["-C", ROOT, "log", "origin/main..HEAD", `--format=%H%x1f%an <%ae>%x1f%s%x1f%b%x1e`],
    { encoding: "utf8" },
  );
  const commits = out
    .split(RECORD_SEP)
    .map((c) => c.trim())
    .filter((c) => c !== "")
    .map((c) => {
      const [hash, author, subject, body] = c.split(FIELD_SEP);
      return { hash, author, subject, body: body ?? "" };
    });
  return { available: true, commits };
}

if (!IS_COMMAND) {
  // imported for its functions; nothing to do
} else if (process.argv.includes("--self-test")) {
  selfTest();
} else {
  const failures = [];
  const files = trackedFiles();
  const scanned = [];
  const skipped = [];

  for (const file of files) {
    if (isBinaryPath(file)) {
      skipped.push(file);
      continue;
    }
    let text;
    try {
      text = readFileSync(join(ROOT, file), "utf8");
    } catch {
      // A tracked file we cannot read is a FAILURE, never a silent skip —
      // the same rule check-styles.mjs learned the hard way.
      failures.push({ file, line: 0, code: "unreadable", detail: "tracked file could not be read as text" });
      continue;
    }
    scanned.push(file);
    const lines = text.split("\n");
    for (let i = 0; i < lines.length; i += 1) {
      const line = lines[i];
      for (const hit of bannedWordHits(line)) {
        failures.push({
          file, line: i + 1, code: "banned-word",
          detail: `the word "${hit.word}" is used, not named. The team's word for sample records is "fixture"; a generated dataset is "synthetic".`,
        });
      }
      for (const hit of attributionHits(line)) {
        failures.push({
          file, line: i + 1, code: hit.code,
          detail: "an assistant is credited as a contributor. Work in this repo is authored by the developer alone.",
        });
      }
    }
  }

  const { available, commits } = newCommits();
  for (const c of commits) {
    for (const hit of assistantAuthorHits(c.author)) {
      failures.push({
        file: `commit ${c.hash.slice(0, 8)}`, line: 0, code: "assistant-author",
        detail: `authored by "${c.author}" — the name "${hit.name}" is an assistant.`,
      });
    }
    for (const line of `${c.subject}\n${c.body}`.split("\n")) {
      for (const hit of attributionHits(line)) {
        failures.push({
          file: `commit ${c.hash.slice(0, 8)}`, line: 0, code: hit.code,
          detail: `commit message line: ${line.trim().slice(0, 90)}`,
        });
      }
    }
  }

  /* STATE THE NEGATIVE. A silent pass is indistinguishable from a broken
   * gate, so the counts are always printed — including the ones that make
   * the gate look small. */
  console.log(
    `check-language: ${scanned.length} tracked text files scanned for ${BANNED_WORDS.length} banned words ` +
      `and ${ATTRIBUTION_PATTERNS.length} attribution patterns; ${skipped.length} binary files skipped.`,
  );
  console.log(
    available
      ? `check-language: ${commits.length} commit${commits.length === 1 ? "" : "s"} ahead of origin/main scanned for assistant attribution.`
      : "check-language: origin/main is not present here, so 0 commits were scanned. File contents were still checked.",
  );

  if (failures.length === 0) {
    console.log("check-language: no banned words in use, no assistant credited. PASS");
  } else {
    for (const f of failures) {
      console.error(`  ${f.code} · ${f.file}${f.line > 0 ? `:${f.line}` : ""} · ${f.detail}`);
    }
    console.error(`check-language: ${failures.length} violation${failures.length === 1 ? "" : "s"}. FAIL`);
    process.exit(1);
  }
}
